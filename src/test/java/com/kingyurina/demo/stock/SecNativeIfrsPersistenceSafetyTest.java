package com.kingyurina.demo.stock;

import static org.junit.jupiter.api.Assertions.*;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.List;
import java.util.UUID;

import org.apache.ibatis.builder.xml.XMLMapperBuilder;
import org.apache.ibatis.mapping.Environment;
import org.apache.ibatis.session.Configuration;
import org.apache.ibatis.session.SqlSession;
import org.apache.ibatis.session.SqlSessionFactoryBuilder;
import org.apache.ibatis.transaction.jdbc.JdbcTransactionFactory;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.support.StaticListableBeanFactory;

import tools.jackson.databind.ObjectMapper;

class SecNativeIfrsPersistenceSafetyTest {
    private Configuration configuration;

    @BeforeEach
    void database() throws Exception {
        var source = new JdbcDataSource();
        source.setURL("jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=MySQL;DB_CLOSE_DELAY=-1");
        try (var connection = source.getConnection(); var statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE stock_sec_financial_standard (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    symbol VARCHAR(20), cik VARCHAR(20), fiscal_year INT, fiscal_period VARCHAR(3),
                    form VARCHAR(10), filed_at DATE, start_date DATE, end_date DATE, accession_number VARCHAR(40),
                    period_days INT, currency VARCHAR(3), revenue DECIMAL(24,4), operating_income DECIMAL(24,4),
                    net_income DECIMAL(24,4), eps_diluted DECIMAL(24,4), assets DECIMAL(24,4),
                    liabilities DECIMAL(24,4), equity DECIMAL(24,4), operating_cash_flow DECIMAL(24,4),
                    eps_unit VARCHAR(40), raw_json CLOB, mapped_at TIMESTAMP,
                    UNIQUE(symbol, fiscal_year, fiscal_period, form, end_date, accession_number))
                    """);
        }
        configuration = new Configuration(new Environment("native-persistence-test", new JdbcTransactionFactory(), source));
        configuration.setMapUnderscoreToCamelCase(true);
        String resource = "mapper/stock/SecFinancialStandardMapper.xml";
        try (var input = getClass().getClassLoader().getResourceAsStream(resource)) {
            new XMLMapperBuilder(input, configuration, resource, configuration.getSqlFragments()).parse();
        }
    }

    @Test
    void partialNativeRebuildPreservesHistoricalAnnualAndUpsertsOnlyProducedQuarter() {
        try (var session = session()) {
            var mapper = session.getMapper(SecFinancialStandardMapper.class);
            mapper.upsertBatch(List.of(historicalAnnual()));
            var service = service(mapper);
            assertEquals(1, service.rebuildFromFacts("GFS", "0001709048", List.of(nativeQuarter())));
            assertEquals(2, mapper.countBySymbol("GFS"));
            assertEquals(0, new BigDecimal("100").compareTo(mapper.findLatestAnnual("GFS").getRevenue()));
            assertEquals(0, new BigDecimal("1688000000").compareTo(mapper.findLatestQuarter("GFS").getRevenue()));
            assertEquals(1, service.rebuildFromFacts("GFS", "0001709048", List.of(nativeQuarter())));
            assertEquals(2, mapper.countBySymbol("GFS")); // Stable produced key, not a duplicate or a full replacement.
        }
    }

    @Test
    void unsupportedNativePeriodCannotEraseExistingHistory() {
        try (var session = session()) {
            var mapper = session.getMapper(SecFinancialStandardMapper.class);
            mapper.upsertBatch(List.of(historicalAnnual()));
            var cumulative = nativeQuarter(); cumulative.setStartDate(LocalDate.of(2025, 1, 1)); cumulative.setFrame(null);
            assertEquals(0, service(mapper).rebuildFromFacts("GFS", "0001709048", List.of(cumulative)));
            assertEquals(1, mapper.countBySymbol("GFS"));
            assertEquals("original-annual", mapper.findLatestAnnual("GFS").getAccessionNumber());
        }
    }

    @Test
    void sameNativeKeyPreservesEntireRichStatementInsteadOfOverwritingItWithPartialFields() throws Exception {
        try (var session = session()) {
            var mapper = session.getMapper(SecFinancialStandardMapper.class);
            var rich = historicalAnnual();
            rich.setFiscalYear(2025); rich.setFiscalPeriod("Q3"); rich.setForm("6-K");
            rich.setFiledAt(LocalDate.of(2025, 11, 12)); rich.setStartDate(LocalDate.of(2025, 7, 1));
            rich.setEndDate(LocalDate.of(2025, 9, 30)); rich.setPeriodDays(92);
            rich.setAccessionNumber("0001709048-25-000071"); rich.setRevenue(new BigDecimal("1688000000"));
            rich.setOperatingIncome(new BigDecimal("195000000")); rich.setNetIncome(new BigDecimal("248000000"));
            rich.setEpsDiluted(new BigDecimal("0.44")); rich.setAssets(new BigDecimal("16708000000"));
            rich.setLiabilities(new BigDecimal("4942000000")); rich.setEquity(new BigDecimal("11712000000"));
            rich.setOperatingCashFlow(new BigDecimal("300")); rich.setEpsUnit("USD/shares");
            rich.setRawJson("{\"originalEvidence\":\"complete-coherent-statement\"}");
            mapper.upsertBatch(List.of(rich));
            var json = new ObjectMapper();
            String originalSnapshot = json.writeValueAsString(mapper.findLatestQuarter("GFS"));
            var partial = nativeQuarter(); partial.setValue(new BigDecimal("42")); partial.setUnit("GBP");
            var service = service(mapper);
            service.rebuildFromFacts("GFS", "0001709048", List.of(partial));
            service.rebuildFromFacts("GFS", "0001709048", List.of(partial));
            assertEquals(1, mapper.countBySymbol("GFS"));
            var retained = mapper.findLatestQuarter("GFS");
            assertEquals("USD", retained.getCurrency());
            assertEquals(0, new BigDecimal("1688000000").compareTo(retained.getRevenue()));
            assertEquals(0, new BigDecimal("248000000").compareTo(retained.getNetIncome()));
            assertEquals("{\"originalEvidence\":\"complete-coherent-statement\"}", retained.getRawJson());
            assertEquals(originalSnapshot, json.writeValueAsString(retained));
            var amendment = nativeQuarter(); amendment.setForm("6-K/A"); amendment.setAccessionNumber("new-amendment");
            service.rebuildFromFacts("GFS", "0001709048", List.of(amendment));
            assertEquals(2, mapper.countBySymbol("GFS"));
        }
    }

    @Test
    void emptyInputIsNoOpRatherThanImplicitDeleteRequest() {
        try (var session = session()) {
            var mapper = session.getMapper(SecFinancialStandardMapper.class);
            mapper.upsertBatch(List.of(historicalAnnual()));
            assertEquals(0, service(mapper).rebuildFromFacts("GFS", "0001709048", List.of()));
            assertEquals(0, service(mapper).rebuildFromFacts("GFS", "0001709048", null));
            assertEquals(1, mapper.countBySymbol("GFS"));
        }
    }

    @Test
    void foreignSixKUsingUsGaapAlsoPreservesHistoricalStandards() {
        try (var session = session()) {
            var mapper = session.getMapper(SecFinancialStandardMapper.class);
            mapper.upsertBatch(List.of(historicalAnnual()));
            var interim = nativeQuarter(); interim.setTaxonomy("us-gaap"); interim.setConcept("Revenues");
            assertEquals(1, service(mapper).rebuildFromFacts("GFS", "0001709048", List.of(interim)));
            assertEquals(2, mapper.countBySymbol("GFS"));
        }
    }

    @Test
    void domesticNonemptyRebuildKeepsExistingReplacementBehavior() {
        try (var session = session()) {
            var mapper = session.getMapper(SecFinancialStandardMapper.class);
            mapper.upsertBatch(List.of(historicalAnnual()));
            var domestic = nativeQuarter(); domestic.setTaxonomy("us-gaap"); domestic.setConcept("Revenues");
            domestic.setForm("10-Q"); domestic.setFiscalYear(2025); domestic.setFiscalPeriod("Q3");
            assertEquals(1, service(mapper).rebuildFromFacts("GFS", "0001709048", List.of(domestic)));
            assertEquals(1, mapper.countBySymbol("GFS"));
            assertNull(mapper.findLatestAnnual("GFS"));
            assertNotNull(mapper.findLatestQuarter("GFS"));
        }
    }

    private SqlSession session() {
        return new SqlSessionFactoryBuilder().build(configuration).openSession();
    }

    private static SecFinancialStandardService service(SecFinancialStandardMapper mapper) {
        var factory = new StaticListableBeanFactory(); factory.addBean("standards", mapper);
        return new SecFinancialStandardService(null, factory.getBeanProvider(SecFinancialStandardMapper.class), new ObjectMapper());
    }

    private static SecFinancialStandard historicalAnnual() {
        var row = new SecFinancialStandard(); row.setSymbol("GFS"); row.setCik("0001709048");
        row.setFiscalYear(2024); row.setFiscalPeriod("FY"); row.setForm("20-F");
        row.setFiledAt(LocalDate.of(2025, 3, 20)); row.setStartDate(LocalDate.of(2024, 1, 1));
        row.setEndDate(LocalDate.of(2024, 12, 31)); row.setPeriodDays(366); row.setCurrency("USD");
        row.setRevenue(new BigDecimal("100")); row.setAccessionNumber("original-annual");
        row.setMappedAt(LocalDateTime.of(2025, 3, 21, 0, 0)); return row;
    }

    private static SecCompanyFact nativeQuarter() {
        var fact = new SecCompanyFact(); fact.setSymbol("GFS"); fact.setCik("0001709048");
        fact.setTaxonomy("ifrs-full"); fact.setConcept("Revenue"); fact.setUnit("USD");
        fact.setValue(new BigDecimal("1688000000")); fact.setForm("6-K");
        fact.setStartDate(LocalDate.of(2025, 7, 1)); fact.setEndDate(LocalDate.of(2025, 9, 30));
        fact.setFrame("CY2025Q3"); fact.setFiledAt(LocalDate.of(2025, 11, 12));
        fact.setAccessionNumber("0001709048-25-000071"); return fact;
    }
}

package com.kingyurina.demo.stock;

import static org.junit.jupiter.api.Assertions.*;

import java.io.InputStream;
import java.sql.Connection;
import java.time.LocalDate;
import java.util.UUID;
import org.apache.ibatis.builder.xml.XMLMapperBuilder;
import org.apache.ibatis.mapping.Environment;
import org.apache.ibatis.session.Configuration;
import org.apache.ibatis.session.SqlSession;
import org.apache.ibatis.session.SqlSessionFactoryBuilder;
import org.apache.ibatis.transaction.jdbc.JdbcTransactionFactory;
import org.h2.jdbcx.JdbcDataSource;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

class FinancialSelectionIntegrationTest {
    private JdbcDataSource source;
    private Configuration configuration;

    @BeforeEach
    void database() throws Exception {
        source = new JdbcDataSource();
        source.setURL("jdbc:h2:mem:" + UUID.randomUUID() + ";MODE=MySQL;DB_CLOSE_DELAY=-1");
        try (Connection connection = source.getConnection(); var statement = connection.createStatement()) {
            statement.execute("""
                    CREATE TABLE stock_sec_financial_standard (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    symbol VARCHAR(20), fiscal_period VARCHAR(3), form VARCHAR(10), filed_at DATE,
                    start_date DATE, end_date DATE, period_days INT, currency VARCHAR(3),
                    revenue DECIMAL(20,4), net_income DECIMAL(20,4), assets DECIMAL(20,4), equity DECIMAL(20,4),
                    eps_diluted DECIMAL(20,4), eps_unit VARCHAR(40))
                    """);
        }
        configuration = new Configuration(new Environment("financial-test", new JdbcTransactionFactory(), source));
        configuration.setMapUnderscoreToCamelCase(true);
        for (String name : new String[] {"HistoricalBacktestSeedMapper", "SecFinancialStandardMapper"}) {
            String resource = "mapper/stock/" + name + ".xml";
            try (InputStream input = getClass().getClassLoader().getResourceAsStream(resource)) {
                new XMLMapperBuilder(input, configuration, resource, configuration.getSqlFragments()).parse();
            }
        }
    }

    @Test
    void nineMonthFyCannotDisplaceActualAnnualInHistoricalOrCurrentReads() throws Exception {
        insert("ALNY", "FY", "2024-01-01", "2024-12-31", 366, "2025-02-01", "USD");
        insert("ALNY", "FY", "2025-01-01", "2025-09-30", 273, "2025-10-01", "USD");
        try (SqlSession session = session()) {
            var current = session.getMapper(SecFinancialStandardMapper.class).findLatestAnnual("ALNY");
            var historical = session.getMapper(HistoricalBacktestSeedMapper.class)
                    .findLatestAnnualAsOf("ALNY", LocalDate.of(2025, 11, 1));
            assertEquals(LocalDate.of(2024, 12, 31), current.getEndDate());
            assertEquals(LocalDate.of(2024, 12, 31), historical.getEndDate());
        }
    }

    @Test
    void yearToDateCannotDisplaceStandaloneQuarterInEitherReadPath() throws Exception {
        insert("TEST", "Q1", "2025-01-01", "2025-03-31", 90, "2025-05-01", "USD");
        insert("TEST", "Q2", "2025-01-01", "2025-06-30", 181, "2025-08-01", "USD");
        try (SqlSession session = session()) {
            assertEquals(LocalDate.of(2025, 3, 31), session.getMapper(SecFinancialStandardMapper.class)
                    .findLatestQuarter("TEST").getEndDate());
            assertEquals(LocalDate.of(2025, 3, 31), session.getMapper(HistoricalBacktestSeedMapper.class)
                    .findLatestQuarterAsOf("TEST", LocalDate.of(2025, 9, 1)).getEndDate());
        }
    }

    @Test
    void unknownFilingTimeIsAvailableOnlyFromFollowingDayForAllHistoricalReads() throws Exception {
        insert("TEST", "FY", "2024-01-01", "2024-12-31", 366, "2025-02-01", "USD");
        insert("TEST", "Q1", "2025-01-01", "2025-03-31", 90, "2025-05-01", "USD");
        try (SqlSession session = session()) {
            var mapper = session.getMapper(HistoricalBacktestSeedMapper.class);
            assertNull(mapper.findLatestAnnualAsOf("TEST", LocalDate.of(2025, 2, 1)));
            assertNull(mapper.findPreviousAnnualAsOf("TEST", LocalDate.of(2025, 12, 31), LocalDate.of(2025, 2, 1)));
            assertNotNull(mapper.findLatestAnnualAsOf("TEST", LocalDate.of(2025, 2, 2)));
            assertNull(mapper.findLatestQuarterAsOf("TEST", LocalDate.of(2025, 5, 1)));
            assertNull(mapper.findPreviousQuarterAsOf("TEST", LocalDate.of(2025, 6, 30), LocalDate.of(2025, 5, 1)));
            assertNotNull(mapper.findLatestQuarterAsOf("TEST", LocalDate.of(2025, 5, 2)));
        }
    }

    @Test
    void olderPeriodAcrossMissingAnnualOrQuarterIsNotAnAdjacentComparison() throws Exception {
        insert("TEST", "FY", "2022-01-01", "2022-12-31", 365, "2023-02-01", "USD");
        insert("TEST", "Q1", "2024-01-01", "2024-03-31", 91, "2024-05-01", "USD");
        try (SqlSession session = session()) {
            var current = session.getMapper(SecFinancialStandardMapper.class);
            var historical = session.getMapper(HistoricalBacktestSeedMapper.class);
            assertNull(current.findPreviousAnnual("TEST", LocalDate.of(2024, 12, 31)));
            assertNull(historical.findPreviousAnnualAsOf("TEST", LocalDate.of(2024, 12, 31), LocalDate.of(2025, 5, 1)));
            assertNull(current.findPreviousQuarter("TEST", LocalDate.of(2024, 9, 30)));
            assertNull(historical.findPreviousQuarterAsOf("TEST", LocalDate.of(2024, 9, 30), LocalDate.of(2025, 5, 1)));
        }
    }

    @Test
    void durationBoundsRejectTenMonthAndExtendedQuarterButKeepFiftyThreeWeekAnnual() throws Exception {
        insert("TEST", "FY", "2023-12-31", "2025-01-04", 371, "2025-02-01", "USD");
        insert("TEST", "FY", "2025-01-01", "2025-11-16", 320, "2025-12-01", "USD");
        insert("TEST", "Q1", "2025-01-01", "2025-03-31", 90, "2025-05-01", "USD");
        insert("TEST", "Q2", "2025-04-01", "2025-07-24", 115, "2025-08-01", "USD");
        try (SqlSession session = session()) {
            var current = session.getMapper(SecFinancialStandardMapper.class);
            var historical = session.getMapper(HistoricalBacktestSeedMapper.class);
            assertEquals(LocalDate.of(2025, 1, 4), current.findLatestAnnual("TEST").getEndDate());
            assertEquals(LocalDate.of(2025, 1, 4), historical.findLatestAnnualAsOf("TEST", LocalDate.of(2026, 1, 1)).getEndDate());
            assertEquals(LocalDate.of(2025, 3, 31), current.findLatestQuarter("TEST").getEndDate());
            assertEquals(LocalDate.of(2025, 3, 31), historical.findLatestQuarterAsOf("TEST", LocalDate.of(2026, 1, 1)).getEndDate());
        }
    }

    private SqlSession session() {
        return new SqlSessionFactoryBuilder().build(configuration).openSession();
    }

    private void insert(String symbol, String period, String start, String end, int days, String filed,
            String currency) throws Exception {
        try (var connection = source.getConnection(); var statement = connection.prepareStatement("""
                INSERT INTO stock_sec_financial_standard
                (symbol, fiscal_period, form, start_date, end_date, period_days, filed_at, currency, revenue, net_income)
                VALUES (?, ?, '10-K', ?, ?, ?, ?, ?, 100, 20)
                """)) {
            statement.setString(1, symbol); statement.setString(2, period);
            statement.setString(3, start); statement.setString(4, end); statement.setInt(5, days);
            statement.setString(6, filed); statement.setString(7, currency); statement.executeUpdate();
        }
    }
}
